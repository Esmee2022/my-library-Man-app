-- Cloud authentication persistence. Existing local SQLite data is copied with
-- scripts/migrate_auth_to_supabase.js after this migration is applied.
create table if not exists public.auth_users (
  id bigint generated by default as identity primary key,
  email text not null unique,
  name text,
  password_hash text not null,
  salt text not null,
  role text not null check (role in ('inputer','manager','admin','administrator')),
  active boolean not null default true,
  password_changed_at timestamptz not null default now(),
  totp_secret text,
  totp_enrolled boolean not null default false,
  failed_login_attempts integer not null default 0 check (failed_login_attempts >= 0),
  locked_until bigint,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists auth_users_email_idx on public.auth_users(lower(email));

create table if not exists public.auth_sessions (
  id text primary key,
  user_id bigint not null references public.auth_users(id) on delete cascade,
  csrf_token text not null,
  expires_at bigint not null,
  last_activity bigint not null,
  created_at bigint not null
);
create index if not exists auth_sessions_user_idx on public.auth_sessions(user_id);
create index if not exists auth_sessions_expiry_idx on public.auth_sessions(expires_at);

create table if not exists public.auth_recovery_codes (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.auth_users(id) on delete cascade,
  code_hash text not null,
  used boolean not null default false,
  used_at timestamptz,
  created_at timestamptz not null default now(),
  unique(user_id,code_hash)
);
create index if not exists auth_recovery_codes_user_idx on public.auth_recovery_codes(user_id) where not used;

create table if not exists public.auth_audit_log (
  id bigint generated by default as identity primary key,
  user_id bigint references public.auth_users(id) on delete set null,
  action text not null,
  ip_address text,
  user_agent text,
  status text not null check (status in ('SUCCESS','FAILURE')),
  details text,
  timestamp timestamptz not null default now()
);
create index if not exists auth_audit_log_time_idx on public.auth_audit_log(timestamp desc);

create table if not exists public.auth_challenges (
  token_hash text primary key,
  user_id bigint not null references public.auth_users(id) on delete cascade,
  expires_at bigint not null,
  created_at timestamptz not null default now()
);
create index if not exists auth_challenges_expiry_idx on public.auth_challenges(expires_at);

alter table public.auth_users enable row level security;
alter table public.auth_sessions enable row level security;
alter table public.auth_recovery_codes enable row level security;
alter table public.auth_audit_log enable row level security;
alter table public.auth_challenges enable row level security;
revoke all on public.auth_users,public.auth_sessions,public.auth_recovery_codes,public.auth_audit_log,public.auth_challenges from anon,authenticated;
grant all on public.auth_users,public.auth_sessions,public.auth_recovery_codes,public.auth_audit_log,public.auth_challenges to service_role;
grant usage,select on sequence public.auth_users_id_seq,public.auth_recovery_codes_id_seq,public.auth_audit_log_id_seq to service_role;

create or replace function public.auth_finish_import()
returns void language plpgsql security definer set search_path=public as $$
begin
  if exists(select 1 from auth_users) then
    perform setval(pg_get_serial_sequence('public.auth_users','id'), coalesce((select max(id) from auth_users),1), true);
  end if;
  if exists(select 1 from auth_recovery_codes) then
    perform setval(pg_get_serial_sequence('public.auth_recovery_codes','id'), coalesce((select max(id) from auth_recovery_codes),1), true);
  end if;
  if exists(select 1 from auth_audit_log) then
    perform setval(pg_get_serial_sequence('public.auth_audit_log','id'), coalesce((select max(id) from auth_audit_log),1), true);
  end if;
end $$;
revoke all on function public.auth_finish_import() from public,anon,authenticated;
grant execute on function public.auth_finish_import() to service_role;

create or replace function public.auth_consume_recovery_code(p_user_id bigint,p_code_hash text)
returns boolean language plpgsql security definer set search_path=public as $$
begin
  update auth_recovery_codes set used=true,used_at=now()
   where user_id=p_user_id and code_hash=p_code_hash and used=false;
  return found;
end $$;
revoke all on function public.auth_consume_recovery_code(bigint,text) from public,anon,authenticated;
grant execute on function public.auth_consume_recovery_code(bigint,text) to service_role;
